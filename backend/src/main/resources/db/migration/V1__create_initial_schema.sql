CREATE TABLE upload_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type VARCHAR(255) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    checksum VARCHAR(255) NOT NULL,
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(255) NOT NULL,
    row_count INTEGER NOT NULL,
    error_message TEXT
);

CREATE TABLE csv_product_source (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upload_batch_id BIGINT NOT NULL,
    row_number INTEGER NOT NULL,
    sku VARCHAR(255),
    product_name VARCHAR(255),
    gross_price_huf NUMERIC(38, 2),
    stock_qty INTEGER,
    brand VARCHAR(255),
    raw_data TEXT,
    CONSTRAINT fk_csv_product_source_upload_batch
        FOREIGN KEY (upload_batch_id) REFERENCES upload_batch (id)
);

CREATE TABLE json_product_source (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upload_batch_id BIGINT NOT NULL,
    row_number INTEGER NOT NULL,
    source_id VARCHAR(255),
    name VARCHAR(255),
    net_price NUMERIC(38, 2),
    currency VARCHAR(255),
    vat_rate NUMERIC(38, 2),
    quantity_available INTEGER,
    manufacturer VARCHAR(255),
    ean VARCHAR(255),
    updated_at TIMESTAMP WITH TIME ZONE,
    raw_data TEXT,
    CONSTRAINT fk_json_product_source_upload_batch
        FOREIGN KEY (upload_batch_id) REFERENCES upload_batch (id)
);

CREATE TABLE processing_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    csv_batch_id BIGINT NOT NULL,
    json_batch_id BIGINT NOT NULL,
    primary_source VARCHAR(255) NOT NULL,
    fallback_missing_values BOOLEAN NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    status VARCHAR(255) NOT NULL,
    valid_count INTEGER,
    invalid_count INTEGER,
    CONSTRAINT fk_processing_run_csv_batch
        FOREIGN KEY (csv_batch_id) REFERENCES upload_batch (id),
    CONSTRAINT fk_processing_run_json_batch
        FOREIGN KEY (json_batch_id) REFERENCES upload_batch (id)
);

CREATE TABLE normalized_product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    processing_run_id BIGINT NOT NULL,
    sku VARCHAR(255),
    name VARCHAR(255),
    manufacturer VARCHAR(255),
    final_price_huf NUMERIC(38, 2),
    stock INTEGER,
    ean VARCHAR(255),
    updated_at TIMESTAMP WITH TIME ZONE,
    source VARCHAR(255),
    primary_source VARCHAR(255) NOT NULL,
    valid BOOLEAN NOT NULL,
    CONSTRAINT fk_normalized_product_processing_run
        FOREIGN KEY (processing_run_id) REFERENCES processing_run (id)
);

CREATE TABLE normalized_product_issue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    normalized_product_id BIGINT NOT NULL,
    code VARCHAR(255) NOT NULL,
    field VARCHAR(255) NOT NULL,
    message VARCHAR(255) NOT NULL,
    severity VARCHAR(255) NOT NULL,
    CONSTRAINT fk_normalized_product_issue_product
        FOREIGN KEY (normalized_product_id) REFERENCES normalized_product (id)
);

CREATE INDEX idx_csv_product_source_upload_batch_id
    ON csv_product_source (upload_batch_id);

CREATE INDEX idx_json_product_source_upload_batch_id
    ON json_product_source (upload_batch_id);

CREATE INDEX idx_processing_run_status_started_at
    ON processing_run (status, started_at DESC);

CREATE INDEX idx_processing_run_csv_batch_id
    ON processing_run (csv_batch_id);

CREATE INDEX idx_processing_run_json_batch_id
    ON processing_run (json_batch_id);

CREATE INDEX idx_normalized_product_processing_run_id
    ON normalized_product (processing_run_id);

CREATE INDEX idx_normalized_product_processing_run_valid
    ON normalized_product (processing_run_id, valid);

CREATE INDEX idx_normalized_product_sku
    ON normalized_product (sku);

CREATE INDEX idx_normalized_product_ean
    ON normalized_product (ean);

CREATE INDEX idx_normalized_product_issue_product_id
    ON normalized_product_issue (normalized_product_id);
